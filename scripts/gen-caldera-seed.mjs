#!/usr/bin/env node
// Generate src/seed/caldera.ts from the Caldera case-study document
// (docs/case-study/caldera/document). Run from the repo root:
//
//   node scripts/gen-caldera-seed.mjs
//
// The emitted module inlines every document file as a JSON-string constant — the
// seed portability rule (src/seed/document.ts): plain string constants, never
// bundler-specific ?raw / import.meta.glob imports, which break on immediately.run.
// Regenerate whenever the case-study document changes; the diff is reviewable.

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const DOC_ROOT = 'docs/case-study/caldera/document';
const OUT = 'src/seed/caldera.ts';

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

const files = walk(DOC_ROOT).sort();
const entries = files.map((p) => `  ${JSON.stringify(`caldera/${relative(DOC_ROOT, p)}`)}: ${JSON.stringify(readFileSync(p, 'utf8'))},`);

const body = `// GENERATED by scripts/gen-caldera-seed.mjs from ${DOC_ROOT} — do not edit by hand;
// regenerate with \`node scripts/gen-caldera-seed.mjs\`. The Caldera LBO case-study
// document inlined as plain string constants for memoryReader (the seed portability
// rule: no bundler-specific ?raw / import.meta.glob, which break on immediately.run).
// The live demo branch serves this as the app's document (src/App.tsx → CALDERA_SEED).

export const CALDERA_ROOT = 'caldera';

export const CALDERA_FILES: Record<string, string> = {
${entries.join('\n')}
};
`;

writeFileSync(OUT, body);
console.log(`wrote ${OUT} (${files.length} files inlined)`);
